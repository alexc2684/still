import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const output = process.env.STILL_SCREENSHOTS || '/tmp'
const browser = await chromium.launch({ headless: true })
try {
  for (const [width, height] of [[375, 812], [375, 667], [375, 568], [1440, 1000]]) {
    const page = await browser.newPage({ viewport: { width, height } })
    page.setDefaultTimeout(10000)
    await page.route('**/api/**', async route => {
      const url = new URL(route.request().url()); let body = {}
      if (url.pathname === '/api/auth/me') body = { user: { id: 'dial-fixture', name: 'Alex', timezone: 'UTC' } }
      if (url.pathname === '/api/sessions') body = { date: '2026-10-01', summary: { totalSessions: 0, totalMinutes: 0 }, sessions: [], practiceDates: [] }
      if (url.pathname === '/api/sessions/start') body = { session: { id: 'dial-session', startedAt: new Date().toISOString(), plannedSeconds: route.request().postDataJSON().plannedSeconds } }
      await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(body) })
    })
    await page.goto('http://localhost:3217', { waitUntil: 'domcontentloaded' })
    const dial = page.locator('.practice-timer-card .timer-dial')
    await page.getByRole('button', { name: /Begin practice/ }).waitFor()
    assert.equal(await page.getByRole('combobox', { name: 'Practice' }).count(), 0)
    assert.equal(await page.locator('.practice-stats, .streak-pill').count(), 0)
    await page.mouse.move(width / 2, 180); await page.mouse.wheel(0, 500)
    await page.waitForTimeout(100)
    assert.equal(await page.evaluate(() => window.scrollY), 0)
    assert.equal(await page.evaluate(() => document.documentElement.scrollHeight <= innerHeight), true)
    const slider = page.getByRole('slider', { name: 'Duration in minutes' })
    await slider.focus(); await page.keyboard.press('ArrowRight')
    assert.equal(await slider.getAttribute('aria-valuenow'), '11')
    const box = await dial.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height * .05)
    await page.mouse.down()
    await page.mouse.move(box.x + box.width * .95, box.y + box.height / 2, { steps: 15 })
    await page.mouse.up()
    assert.notEqual(await slider.getAttribute('aria-valuenow'), '11')
    assert.equal(await dial.locator('input').count(), 0)
    await slider.focus(); await page.keyboard.press('Home')
    for (let minute = 1; minute < 20; minute++) await page.keyboard.press('ArrowUp')
    await slider.blur()
    await page.waitForTimeout(500)
    await page.screenshot({ path: `${output}/sit-clean-idle-${width}-${height}.png`, fullPage: true })
    const cta = await page.getByRole('button', { name: /Begin practice/ }).boundingBox()
    const nav = await page.locator('.bottom-nav').boundingBox()
    assert.ok(cta.y + cta.height <= nav.y - 8, 'Start control must clear bottom navigation')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true)
    await page.getByRole('button', { name: /Begin practice/ }).click()
    await page.getByRole('button', { name: 'Pause', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: /End session/ }).count(), 0)
    assert.equal(await dial.locator('.timer-dial-aura').evaluate(el => getComputedStyle(el).animationName), 'dial-breathe')
    await page.screenshot({ path: `${output}/sit-clean-active-${width}-${height}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Pause', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: /End session/ }).count(), 1)
    assert.equal(await dial.locator('.timer-dial-aura').evaluate(el => getComputedStyle(el).animationPlayState), 'paused')
    await page.screenshot({ path: `${output}/sit-clean-paused-${width}-${height}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Resume', exact: true }).click()
    await page.emulateMedia({ reducedMotion: 'reduce' })
    assert.equal(await dial.locator('.timer-dial-aura').evaluate(el => getComputedStyle(el).animationName), 'none')
    assert.equal(await page.getByRole('button', { name: /End session/ }).count(), 0)
    await page.getByRole('button', { name: 'Pause', exact: true }).click()
    await page.getByRole('button', { name: /End session/ }).click()
    await page.getByRole('button', { name: /Begin practice/ }).waitFor()
    await page.getByRole('button', { name: /Journal/ }).click()
    await page.getByRole('heading', { name: 'Journal', exact: true }).waitFor()
    assert.notEqual(await page.evaluate(() => getComputedStyle(document.documentElement).overflow), 'hidden')
    await page.mouse.wheel(0, 500); await page.waitForTimeout(150)
    if (height < 900) assert.ok(await page.evaluate(() => window.scrollY > 0))
    await page.getByRole('button', { name: 'Still', exact: true }).click()
    await page.evaluate(() => localStorage.setItem('still:reflection-session:dial-fixture', 'complete-fixture'))
    await page.reload({ waitUntil: 'domcontentloaded' })
    await page.getByRole('button', { name: /Edit reflection/ }).click()
    const modal = page.locator('.reflection-modal')
    assert.equal(await modal.evaluate(el => getComputedStyle(el).overflowY), 'auto')
    await modal.getByRole('button', { name: /Save reflection/ }).scrollIntoViewIfNeeded()
    assert.ok(await modal.getByRole('button', { name: /Save reflection/ }).isVisible())
    await page.close()
  }
  console.log('Dial-only drag and keyboard controls, start/pause/resume, motion preferences, and layouts passed.')
} finally { await browser.close() }
